import type { CharacterProfile } from "./characterProfile";

/**
 * 官方陪聊角色 — the ten members of 3-A班 from the platform's own IP, seeded
 * into the `official_characters` table by the admin sync route
 * (app/api/admin/official-characters). Personas follow the official
 * character notes exactly where they exist; anything not in the notes is
 * extrapolated from the stated personality.
 *
 * Content rating: canonical ages are kept (16–18). Every character under 18
 * is `all_ages` — strictly a friend / squad-mate companion: the romantic
 * relationship ladder, 解鎖場景, 換裝衣櫃 and any NSFW model routing are all
 * disabled for them (see contentRules in lib/characters.ts and the
 * per-route guards). The two 18-year-olds run on the normal adult ladder.
 * This is the one place ages below 18 are accepted; user-created
 * characters stay 18+.
 */

export type ContentRating = "all_ages" | "adult";

export interface OfficialCharacterSeed {
  key: string;
  name: string;
  /** furigana-ish romanization for file names / UI */
  slug: string;
  roleTitle: string;
  age: number;
  sort: number;
  personality: string;
  likes: string;
  profile: Omit<CharacterProfile, "version">;
  /** three-view sheet in /public/official-characters */
  sheetPath: string;
  /** front-view crop used as the avatar + idle-video reference */
  avatarPath: string;
  /** appearance sentence for the idle-video prompt — deliberately free of age / school-grade terms */
  idleAppearance: string;
}

export function contentRatingForAge(age: number): ContentRating {
  return age >= 18 ? "adult" : "all_ages";
}

